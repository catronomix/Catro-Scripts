"""Build the Linux test image and run the acceptance checks in it.

Stdlib only; wraps `docker build` + `docker run` so one command reproduces the
POSIX oracle on any host with Docker:

    python tests/container/run.py                  # 3.12, base + extras
    python tests/container/run.py --python 3.11,3.12
    python tests/container/run.py --extras 0 --no-build

Artifacts (result JSON + summary) go to .devteam/artifacts/container/ by
default, which is gitignored. The repository is copied into the image at build
time and the container runs read-only with no network, so nothing is ever
written back into the working tree.
"""
import argparse
import json
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
DEFAULT_OUT = os.path.join(ROOT, ".devteam", "artifacts", "container")
JSON_MARK = "###JSON###"


def sh(cmd, cwd=ROOT, timeout=1800):
    return subprocess.run(cmd, cwd=cwd, stdin=subprocess.DEVNULL,
                          stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                          text=True, errors="replace", timeout=timeout)


def docker_run(cmd, timeout=900):
    """Like sh(), but keeps stdout and stderr apart (the JSON lives on stdout)."""
    return subprocess.run(cmd, cwd=ROOT, stdin=subprocess.DEVNULL,
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                          text=True, errors="replace", timeout=timeout)


def docker_ok():
    try:
        p = sh(["docker", "version", "--format", "{{.Server.Version}}"], timeout=60)
    except Exception as exc:
        return False, str(exc)
    return p.returncode == 0, p.stdout.strip()


def build(version, extras, tag):
    cmd = ["docker", "build",
           "-f", os.path.join("tests", "container", "Dockerfile"),
           "--target", "test",
           "--build-arg", "PYTHON_VERSION=" + version,
           "--build-arg", "EXTRAS=" + ("pillow piexif pydub" if extras else ""),
           "-t", tag, "."]
    print("$ " + " ".join(cmd), flush=True)
    started = time.time()
    p = sh(cmd)
    elapsed = time.time() - started
    if p.returncode != 0:
        sys.stderr.write(p.stdout[-6000:])
        raise SystemExit("docker build failed for {} extras={}".format(version, extras))
    size = sh(["docker", "image", "inspect", "-f", "{{.Size}}", tag], timeout=120)
    try:
        size_mb = round(int(size.stdout.strip()) / (1000 * 1000), 1)
    except Exception:
        size_mb = None
    print("[build] {} extras={} {:.1f}s {} MB".format(
        version, int(extras), elapsed, size_mb), flush=True)
    return elapsed, size_mb


def run_checks(version, extras, tag, label, timeout=900):
    cmd = ["docker", "run", "--rm",
           "--network", "none",
           "--read-only",
           "--tmpfs", "/tmp:rw,size=256m",
           "--cap-drop", "ALL",
           "-e", "IMAGE_LABEL=" + label,
           tag,
           "--label", label,
           "--python-version", version,
           "--extras", str(int(extras))]
    print("$ " + " ".join(cmd), flush=True)
    p = docker_run(cmd, timeout=timeout)
    out, err = p.stdout, p.stderr
    doc = None
    idx = out.rfind(JSON_MARK)
    if idx >= 0:
        payload = out[idx + len(JSON_MARK):].lstrip()
        try:
            doc, _ = json.JSONDecoder().raw_decode(payload)
        except Exception as exc:
            err += "\n[unparsable JSON: {}]\n{}".format(exc, payload[:2000])
    print(err.rstrip(), flush=True)
    return p.returncode, doc, err


def summary_rows(rows):
    lines = ["# Linux oracle (docker) results", "",
             "Generated by `tests/container/run.py`; images are built from",
             "`tests/container/Dockerfile` and run read-only without network.", "",
             "| python | layer | probes PASS | USAGE | tty-guard | DEP | SKIP | HANG | FAIL | defects | suite | extras | build | size |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        c = r.get("counts", {}) or {}
        fails = sum(v for k, v in c.items()
                    if k not in ("PASS", "USAGE", "PASS:tty-guard", "DEP", "SKIP"))
        probe = r.get("extras_probe")
        extras_state = ("-" if probe is None
                        else ("ok" if probe.get("ok") else "FAILED"))
        lines.append("| {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {:.1f}s | {} MB |".format(
            r["python"], r["layer"], c.get("PASS", 0), c.get("USAGE", 0),
            c.get("PASS:tty-guard", 0), c.get("DEP", 0), c.get("SKIP", 0),
            c.get("HANG", 0), fails,
            ", ".join(r.get("defects") or []) or "-",
            "ok" if (r.get("suite") or {}).get("ok") else ("skipped" if r.get("suite") is None else "FAILED"),
            extras_state,
            r.get("build_seconds") or 0, r.get("size_mb") or "?"))
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--python", default="3.11,3.12", help="comma-separated versions, e.g. 3.11,3.12")
    ap.add_argument("--extras", default="0,1", help="comma-separated layers: 0=stdlib, 1=extras")
    ap.add_argument("--out", default=DEFAULT_OUT, help="artifact directory (default: .devteam/artifacts/container)")
    ap.add_argument("--no-build", action="store_true", help="reuse existing tags")
    args = ap.parse_args()

    ok, server = docker_ok()
    if not ok:
        raise SystemExit("docker server unavailable: " + server)
    print("[docker] server " + server, flush=True)

    versions = [v.strip() for v in args.python.split(",") if v.strip()]
    layers = [int(v) for v in args.extras.split(",") if v.strip()]
    os.makedirs(args.out, exist_ok=True)

    rows, failed = [], []
    for version in versions:
        for extras in layers:
            layer = "extras" if extras else "base"
            tag = "catro-scripts-test:{}-{}".format(version, layer)
            label = "{}/{}".format(version, layer)
            if args.no_build:
                build_seconds, size_mb = 0.0, None
            else:
                build_seconds, size_mb = build(version, extras, tag)
            rc, doc, err = run_checks(version, extras, tag, label)
            if doc is None:
                sys.stderr.write(err[-4000:])
                failed.append(label + " (no result document, rc={})".format(rc))
                continue
            doc.update(layer=layer, build_seconds=round(build_seconds, 1), size_mb=size_mb)
            rows.append(doc)
            path = os.path.join(args.out, "res-{}-{}.json".format(version, layer))
            with open(path, "w", encoding="utf-8") as fh:
                json.dump(doc, fh, indent=1, sort_keys=True)
            print("[result] {} -> {} (suite {}, {} probes, defects: {})".format(
                label, path,
                "ok" if (doc.get("suite") or {}).get("ok") else "FAILED",
                len(doc.get("results") or []),
                ", ".join(doc.get("defects") or []) or "none"), flush=True)
            if not doc.get("ok") or rc != 0:
                failed.append(label)

    if rows:
        summary = summary_rows(rows)
        with open(os.path.join(args.out, "summary.md"), "w", encoding="utf-8") as fh:
            fh.write(summary)
        print("\n" + summary, flush=True)

    if failed:
        raise SystemExit("FAILED: " + ", ".join(failed))
    print("OK: all requested images passed", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
